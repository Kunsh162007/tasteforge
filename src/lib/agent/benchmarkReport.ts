import { BENCH_KINDS, summarizeByKind, type BenchKind, type KindSummary, type PickOutcome } from "./benchmark";

/** Renders docs/BENCHMARK.md from benchmark results (aggregates, pick names and per-pick fit; never raw Qloo data). */

export type BenchRun = {
  readonly id: string;
  readonly city: string;
  readonly type: string;
  readonly seconds: number;
  readonly grounding: number;
  readonly baseline: readonly PickOutcome[];
  readonly tasteforge: readonly PickOutcome[];
};

export type Consistency = {
  readonly id: string;
  readonly baselineOverlap: number | null;
  readonly tasteforgeOverlap: number | null;
  readonly groundings: readonly [number, number];
  /** Picks in each of the two TasteForge briefs (a run whose Qloo walk came back thin has few). */
  readonly picks: readonly [number, number];
};

export type BenchPrompt = { readonly id: string; readonly city: string; readonly type: string; readonly mode: string; readonly prompt: string };

export type BenchReport = {
  readonly runs: readonly BenchRun[];
  readonly consistency: readonly Consistency[];
  readonly prompts: readonly BenchPrompt[];
  readonly models: readonly string[];
  readonly date: string;
  readonly llmCalls: number;
};

const pct = (n: number | null): string => (n === null ? "n/a" : `${Math.round(n * 100)}%`);
const fit = (n: number | null): string => (n === null ? "n/a" : n.toFixed(2));
const KIND_LABEL: Record<BenchKind, string> = { artist: "Artists", place: "Places", brand: "Brands" };

function kindRows(base: Record<BenchKind, KindSummary>, mine: Record<BenchKind, KindSummary>): string[] {
  return BENCH_KINDS.map((k) => {
    const b = base[k];
    const t = mine[k];
    const off = (s: KindSummary): string => (k === "place" ? `${pct(s.offCityRate)} (${s.offCity}/${s.located})` : "n/a");
    return `| ${KIND_LABEL[k]} | ${b.picks} / ${t.picks} | ${pct(b.notFoundRate)} (${b.notFound}) | ${pct(t.notFoundRate)} (${t.notFound}) | ${off(b)} | ${off(t)} | ${fit(b.meanFit)} | ${fit(t.meanFit)} |`;
  });
}

function headline(base: Record<BenchKind, KindSummary>, mine: Record<BenchKind, KindSummary>): string {
  const b = base.place;
  const t = mine.place;
  const verified = (s: KindSummary): number => (s.unverifiedRate === null ? 0 : 1 - s.unverifiedRate);
  return [
    `- **Places a plain LLM named that Qloo could not confirm in the requested city:** ${pct(b.unverifiedRate)} (${b.notFound} not found, ${b.offCity} in another city, of ${b.picks}). TasteForge: ${pct(t.unverifiedRate)} of ${t.picks}.`,
    `- **Picks Qloo could not find at all (all types):** baseline ${pct(rateOf(base, "notFound"))}, TasteForge ${pct(rateOf(mine, "notFound"))}.`,
    `- **Share of place picks that are verified and local:** baseline ${pct(verified(b))}, TasteForge ${pct(verified(t))}.`,
  ].join("\n");
}

function rateOf(s: Record<BenchKind, KindSummary>, field: "notFound"): number | null {
  const picks = BENCH_KINDS.reduce((n, k) => n + s[k].picks, 0);
  return picks === 0 ? null : BENCH_KINDS.reduce((n, k) => n + s[k][field], 0) / picks;
}

export function renderBenchmark(r: BenchReport): string {
  const base = summarizeByKind(r.runs.flatMap((x) => x.baseline));
  const mine = summarizeByKind(r.runs.flatMap((x) => x.tasteforge));
  const cities = [...new Set(r.prompts.map((p) => p.city))];
  const consistencyRows = r.consistency.map(
    (c) => `| ${c.id} | ${pct(c.baselineOverlap)} | ${pct(c.tasteforgeOverlap)} | ${c.picks.join(" and ")} | ${c.groundings.map((g) => pct(g)).join(" and ")} |`,
  );
  const avg = (f: (c: Consistency) => number | null): number | null => {
    const v = r.consistency.flatMap((c) => (f(c) === null ? [] : [f(c) as number]));
    return v.length === 0 ? null : v.reduce((a, b) => a + b, 0) / v.length;
  };
  return `# Fabrication benchmark

How often does a plain LLM name venues, artists and brands that Qloo cannot confirm, and how does TasteForge compare? Generated by \`npm run benchmark\` on ${r.date}; ${r.runs.length} of ${r.prompts.length} prompts completed.

## Headline

${headline(base, mine)}
- **Repeat-run consistency** (${r.consistency.length} prompts, 2 runs each): picks overlap ${pct(avg((c) => c.baselineOverlap))} for the plain LLM and ${pct(avg((c) => c.tasteforgeOverlap))} for TasteForge.

## Results (${r.runs.length} prompts, ${cities.length} cities: ${cities.join(", ")})

Baseline = the Taste Proof baseline: a plain LLM with no Qloo data, asked for artists, places and brands for the same prompt. TasteForge = the picks in TasteForge's brief. Each pick is checked against Qloo.

| Pick type | Picks (baseline / TasteForge) | Not found: baseline | Not found: TasteForge | Off-city: baseline | Off-city: TasteForge | Mean fit: baseline | Mean fit: TasteForge |
|---|---|---|---|---|---|---|---|
${kindRows(base, mine).join("\n")}

- **Not found**: no Qloo entity of that type has a matching name among the top 5 search hits. Fuzzy hits with a different name do not count, so the baseline gets the benefit of the doubt.
- **Off-city** (places only): the matching entity closest to the city centre lies more than 50 km from it. Counted among found places that have coordinates.
- **Mean fit**: Qloo's affinity for the picks it found, scored against the audience's taste signals with \`filter.results.entities\`. Picks that were not found are left out, never averaged in as zero.
- Mean fit covers ${base.artist.scored + base.place.scored + base.brand.scored} baseline and ${mine.artist.scored + mine.place.scored + mine.brand.scored} TasteForge picks; the others were not found, or Qloo's scoring request timed out.

## Repeat-run consistency

Three prompts, each run twice with the real synthesis step. Overlap is the Jaccard overlap of pick names (1 = identical lists). Every TasteForge brief in these runs was fully grounded; what changes between runs is which questions the language model asks Qloo (its seeds and concept tags) and which of the results it writes up, so the picks differ even though each one is real. Both lists are far from repeatable: the design guarantees grounding, not stability.

| Prompt | Plain LLM overlap | TasteForge overlap | TasteForge picks per run | Grounding of the two briefs |
|---|---|---|---|---|
${consistencyRows.join("\n") || "| not run | | | | |"}

## Method

- **Prompts:** ${r.prompts.length} prompts across ${cities.length} cities, mixing cafes, shops, studios and events, in both modes (listed below). Cities were chosen from \`npm run qloo:check\`, which shows live place, decor/ambience and heatmap coverage for each.
- **Baseline:** one LLM call asking for about 6 artists, 6 places and 4 brands with no Qloo data (the same call the app's Taste Proof makes). Names the user typed into the prompt are removed from both lists, as in the app.
- **TasteForge:** the full hybrid pipeline against live Qloo. In the ${r.prompts.length}-prompt set the synthesis step is replaced by a deterministic writer, so TasteForge's picks are the Qloo entities the walk returned, in order, capped at the same counts as the baseline. This keeps the free LLM quota usable; the six consistency runs use the real synthesis. The real brief can only cite entities from this same evidence, so its not-found and off-city rates are the same by construction; its picks and their fit can differ.
- **Models (fast chain, all calls):** ${r.models.join(", ")}. Real LLM calls used: ${r.llmCalls}.
- **Scoring:** one \`/v2/insights\` call per pick type with \`filter.results.entities\`, using the same audience signals for both lists.

## Prompts

| Id | Mode | Prompt |
|---|---|---|
${r.prompts.map((p) => `| ${p.id} | ${p.mode} | ${p.prompt} |`).join("\n")}

## Per-prompt picks not found or off-city (baseline)

${perPrompt(r.runs)}

## Caveats

- Qloo's catalogue is not the world. A real venue missing from Qloo counts as "not found", so the not-found rate overstates fabrication; it is better read as "cannot be verified or located by Qloo". Indore has far thinner coverage than London or Chicago, and its place results are the most likely to be missing.
- TasteForge returns only what Qloo returned, so its not-found and off-city rates are about 0% by design. That is the point of the architecture, not a measured model skill.
- Affinity measures fit with the audience's taste signals, not quality. A plain LLM that names famous places can still score well on fit. The fit gap is small and varies by prompt; the fabrication gap is the stronger claim.
- A fuzzy name match can be generous: a short chain name can match a branch in another city. We take the closest match, which favours the baseline.
- The baseline model matters. Here the baseline is the fast chain (mostly Groq gpt-oss-120b, which knows fewer local venues than the large Gemini models). Four full runs of the same 20 prompts on 2026-10-20 (different model mixes and small changes to name matching while we built the benchmark) gave 43%, 59%, 47% and 56% of baseline places unverified; read the headline as roughly half, not as a precise rate. TasteForge's 0% does not depend on the baseline model.
- One run of each prompt, 20 prompts, one day: treat percentages as indicative, not as confidence intervals.
- The LLM free tiers change quickly; model names above are what answered on the day.

## Reproduce

\`\`\`bash
# needs QLOO_MODE=live, QLOO_API_KEY and GROQ_API_KEY and/or GEMINI_API_KEY in .env.local
npm run benchmark -- --write
\`\`\`
`;
}

function perPrompt(runs: readonly BenchRun[]): string {
  const lines = runs.flatMap((x) => {
    const bad = x.baseline.filter((p) => !p.found || p.offCity);
    if (bad.length === 0) return [];
    const names = bad.map((p) => `${p.name} (${p.kind}, ${p.found ? "other city" : "not found"})`).join("; ");
    return [`- **${x.id}**: ${names}`];
  });
  return lines.length === 0 ? "None." : lines.join("\n");
}
